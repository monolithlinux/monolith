# theme-2x.txt is theme.txt with every number of pixels doubled, the large
# pictures and the font. theme-2x-logo.txt is theme.txt with only the logo
# doubled. Comments aside, nothing else may differ: sync moves the text in
# by the same rule in all three.
# doubled FILE WHAT: FILE without comments, the pixels of WHAT (all, or logo)
# doubled.
doubled() {
    awk -v what="$2" '
        /^[[:space:]]*#/ || /^[[:space:]]*$/ { next }
        /^\+ image/ { in_logo = 1 }
        /^}/ { closing = 1 }
        {
            line = $0
            if (what == "all" || in_logo) {
                if (match(line, /%-[0-9]+$/))
                    line = substr(line, 1, RSTART + 1) (2 * substr(line, RSTART + 2))
                else if (line ~ /^  (width|item_icon_space|item_height|item_padding|item_spacing|icon_width|icon_height|scrollbar_left_pad) = [0-9]+$/)
                    line = "  " $1 " = " (2 * $3)
                sub(/"logo\.png"/, "\"logo-2x.png\"", line)
                sub(/"select_\*\.png"/, "\"select-2x_*.png\"", line)
            }
            print line
            if (closing) { in_logo = 0; closing = 0 }
        }' "$1"
}
plain() { grep -vE '^[[:space:]]*(#|$)' "$1"; }
