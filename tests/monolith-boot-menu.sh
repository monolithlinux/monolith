#!/usr/bin/env bash
# `monolith boot-menu` and the GRUB theme it keeps on /boot, run against a
# stand-in /boot. The theme itself was checked in the GRUB Monolith ships,
# inside a virtual machine with Secure Boot on and off; this covers the script
# that copies it and the files it copies.
#
# The script learns the screen's size from the kernel and Secure Boot from the
# firmware's variables. Here both are files the test writes.
#
# Not covered here: a /boot that is mounted read-only. That path needs root
# (unshare and mount), which these tests don't have.
set -euo pipefail

repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
libexec="$repo_root/files/system/usr/libexec/monolith"
shipped="$repo_root/files/system/usr/share/monolith/grub"
test_root="$(mktemp -d)"
trap 'chmod -R u+rwx -- "$test_root" 2>/dev/null; rm -rf -- "$test_root"' EXIT

fail() { printf 'FAIL: %s\n' "$*" >&2; exit 1; }
has() { grep -qF -- "$2" <<<"$1" || fail "expected '$2' in:"$'\n'"$1"; }
lacks() { ! grep -qF -- "$2" <<<"$1" || fail "did not expect '$2' in:"$'\n'"$1"; }

bin="$test_root/bin"
boot="$test_root/boot"
grub="$boot/grub2"
vendor="$test_root/usr-share"
# The look as an image has it: this repository's files and the font the build
# makes from GRUB's own (files/scripts/make-boot-menu-font.py).
image="$vendor/monolith/grub"
state="$test_root/state"
run="$test_root/run"
sys="$test_root/sys"
mkdir -p "$bin"
printf '#!/bin/sh\nexec "$@"\n' >"$bin/sudo"
chmod +x "$bin/sudo"
export PATH="$bin:$PATH" MONOLITH_BOOT="$boot" MONOLITH_VENDOR="$vendor" MONOLITH_STATE="$state"
export MONOLITH_RUN="$run" MONOLITH_SYS="$sys"
unset MONOLITH_BOOT_MENU_UNSHARED

begin='### BEGIN Monolith boot menu ###'
end='### END Monolith boot menu ###'
kde_title='Monolith KDE 45.20261112.0 (ostree:0)'
password='GRUB2_PASSWORD=grub.pbkdf2.sha512.10000.0123ABCD.4567EF'

entry() { printf 'title %s\nversion %s\noptions rw quiet\nlinux /vmlinuz\n' "$2" "$1" >"$boot/loader/entries/ostree-$1.conf"; }
menu() { "$libexec/boot-menu" "$@"; }
# offset [FILE]: the text offset in one of the theme's files on /boot.
offset() { sed -n -E 's/^ *item_icon_space = ([0-9]+)$/\1/p' "$grub/themes/monolith/${1:-theme.txt}"; }
count() { grep -cxF -- "$1" "$grub/user.cfg" || true; }
# What must never stay behind after a run.
tidy() {
    local left
    left="$(find "$boot" -name '.monolith.*' -o -name '*.monolith-new')"
    [ -z "$left" ] || fail "left behind: $left"
}

# reset: /boot as bootupd and ostree leave it on a KDE install with two builds,
# the look as this repository ships it, and a computer that says nothing
# about its screen or Secure Boot.
reset() {
    chmod -R u+rwx -- "$boot" 2>/dev/null || true
    rm -rf -- "$boot" "$vendor" "$state" "$run" "$sys"
    mkdir -p "$grub" "$boot/loader/entries" "$vendor/monolith" "$run" "$sys"
    cp -r -- "$shipped" "$image"
    printf 'a stand-in for the font the image build makes\n' >"$image/themes/monolith/unifont-32.pf2"
    # The part of bootupd's static grub.cfg that matters here (its
    # grub2-static/configs.d/01_users.cfg).
    cat >"$grub/grub.cfg" <<'EOF'
# Generated by bootupd / do not edit
set timeout_style=menu
set timeout=1

### BEGIN 01_users.cfg ###
# Keep the comment for grub2-set-password
### BEGIN /etc/grub.d/01_users ###
if [ -f ${prefix}/user.cfg ]; then
  source ${prefix}/user.cfg
  if [ -n "${GRUB2_PASSWORD}" ]; then
    set superusers="root"
    export superusers
    password_pbkdf2 root ${GRUB2_PASSWORD}
  fi
fi
### END 01_users.cfg ###
EOF
    entry 2 "$kde_title"
    entry 1 'Monolith KDE 45.20261111.0 (ostree:1)'
}

# ---- A first start: the look goes onto /boot ---------------------------------
reset
out="$(menu sync)"
has "$out" "Monolith's boot menu look is on /boot. It shows the next time the computer starts."
[ "$(count "$begin")" = 1 ] && [ "$(count "$end")" = 1 ] || fail "user.cfg should have one block: $(cat "$grub/user.cfg")"
[ "$(sed -n 1p "$grub/user.cfg")" = "$begin" ] || fail 'the block does not start the new user.cfg'
[ "$(sed -n '$p' "$grub/user.cfg")" = "$end" ] || fail 'the block does not end user.cfg'
[ "$(sed '1d;$d' "$grub/user.cfg")" = "$(cat "$shipped/user.cfg")" ] || fail 'the block is not the shipped user.cfg'
[ "$(stat -c %a "$grub/user.cfg")" = 600 ] || fail "user.cfg mode: $(stat -c %a "$grub/user.cfg")"
# 116 is right for the KDE edition's titles, so the copy is the shipped theme byte for byte.
diff -r -- "$image/themes/monolith" "$grub/themes/monolith" || fail "the theme on /boot differs from the image's"
[ -f "$grub/themes/monolith/unifont-32.pf2" ] || fail 'the large font did not get to /boot'
[ "$(offset)" = 116 ] || fail "text offset: $(offset)"
[ "$(stat -c %a "$grub/themes/monolith/logo.png")" = 644 ] || fail 'theme files should be 0644'
tidy

# systemd starts the service with next to nothing in its environment: no HOME,
# no TERM, no locale. The script has to work like that.
reset
bare="$(env -i PATH="$PATH" MONOLITH_BOOT="$boot" MONOLITH_VENDOR="$vendor" MONOLITH_STATE="$state" \
    MONOLITH_RUN="$run" MONOLITH_SYS="$sys" "$libexec/boot-menu" sync 2>&1)" ||
    fail "sync failed without HOME and TERM: $bare"
has "$bare" "Monolith's boot menu look is on /boot. It shows the next time the computer starts."
[ "$(offset)" = 116 ] || fail "text offset without a locale: $(offset)"
! grep -n 'common\.sh' "$libexec/boot-menu" | grep -v '^[0-9]*:#' || fail 'boot-menu must not load common.sh, which needs HOME'

# The next start changes nothing.
before="$(stat -c '%i %Y' "$grub/user.cfg" "$grub/themes/monolith" "$grub/themes/monolith/theme.txt")"
out="$(menu sync)"
has "$out" "Monolith's boot menu look is on /boot already."
[ "$(stat -c '%i %Y' "$grub/user.cfg" "$grub/themes/monolith" "$grub/themes/monolith/theme.txt")" = "$before" ] ||
    fail 'a second sync wrote to /boot'
has "$(menu)" "Monolith's boot menu look is on. Turn it off with: monolith boot-menu off"

# ---- The longest entry sits in the middle ------------------------------------
# (560 - 2 * 16 - 8 * letters) / 2, and twice that where everything is twice the size.
entry 3 'Monolith KDE NVIDIA 45.20261113.0 (ostree:0)'
has "$(menu sync)" 'is on /boot. It shows'
[ "$(offset)" = 88 ] || fail "44 letters should give 88, got $(offset)"
[ "$(offset theme-2x-logo.txt)" = 88 ] || fail "44 letters should give 88 under the large logo, got $(offset theme-2x-logo.txt)"
[ "$(offset theme-2x.txt)" = 176 ] || fail "44 letters of twice the width should give 176, got $(offset theme-2x.txt)"
diff -r -x 'theme*.txt' -- "$image/themes/monolith" "$grub/themes/monolith" || fail 'more than the theme files changed'
for file in theme.txt theme-2x.txt theme-2x-logo.txt; do
    [ "$(diff -- "$image/themes/monolith/$file" "$grub/themes/monolith/$file" | grep -c '^[<>]')" = 2 ] ||
        fail "more than one line of $file changed"
done
entry 4 'A title that is far too long to fit into the highlight of the boot menu at all'
menu sync >/dev/null
[ "$(offset)" = 0 ] || fail "a title wider than the highlight should give 0, got $(offset)"
[ "$(offset theme-2x.txt)" = 0 ] || fail "a title wider than the large highlight should give 0, got $(offset theme-2x.txt)"
rm -- "$boot"/loader/entries/*.conf
menu sync >/dev/null
[ "$(offset)" = 176 ] || fail "with no entries, UEFI Firmware Settings (22 letters) should give 176, got $(offset)"
[ "$(offset theme-2x.txt)" = 352 ] || fail "with no entries the large menu should give 352, got $(offset theme-2x.txt)"
tidy

# ---- A GRUB password and lines of your own stay ------------------------------
reset
printf '%s\n# mine\n' "$password" >"$grub/user.cfg"
chmod 600 "$grub/user.cfg"
menu sync >/dev/null
[ "$(sed -n 1p "$grub/user.cfg")" = "$password" ] || fail 'the password line moved or went missing'
[ "$(sed -n 2p "$grub/user.cfg")" = '# mine' ] || fail 'a line outside the block went missing'
[ "$(count "$begin")" = 1 ] || fail 'no block next to the password'
# Changes inside the block are replaced, lines outside are kept.
sed -i 's/^set timeout=5$/set timeout=30/' "$grub/user.cfg"
echo '# after' >>"$grub/user.cfg"
has "$(menu sync)" 'is on /boot. It shows'
grep -qx 'set timeout=5' "$grub/user.cfg" || fail 'a change inside the block survived'
grep -qx '# after' "$grub/user.cfg" || fail 'a line after the block went missing'
[ "$(count "$begin")" = 1 ] && [ "$(count "$end")" = 1 ] || fail 'the block was written twice'
# A block whose end went missing: what follows is dropped, a password is not.
printf '%s\nset timeout=99\n%s\n' "$begin" "$password" >"$grub/user.cfg"
menu sync >/dev/null
grep -qxF -- "$password" "$grub/user.cfg" || fail 'the password inside a cut-off block was lost'
! grep -q 'timeout=99' "$grub/user.cfg" || fail 'a cut-off block was kept'
[ "$(count "$begin")" = 1 ] && [ "$(count "$end")" = 1 ] || fail 'a cut-off block was not replaced by one whole block'

# ---- Off and on --------------------------------------------------------------
reset
printf '%s\n' "$password" >"$grub/user.cfg"
mkdir -p "$grub/themes/another"
menu sync >/dev/null
out="$(menu off)"
has "$out" "Monolith's boot menu look is off /boot. GRUB shows its plain list again, for one second."
[ -e "$state/boot-menu-off" ] || fail 'off left no note'
[ ! -e "$grub/themes/monolith" ] || fail 'off left the theme on /boot'
[ -d "$grub/themes/another" ] || fail "off removed a theme that isn't Monolith's"
[ "$(cat "$grub/user.cfg")" = "$password" ] || fail "off should leave only the password: $(cat "$grub/user.cfg")"
[ "$(stat -c %a "$grub/user.cfg")" = 600 ] || fail 'off changed the mode of user.cfg'
has "$(menu)" "Monolith's boot menu look is off. Turn it on with: monolith boot-menu on"
# The service keeps away while it is off.
has "$(menu sync)" "Monolith's boot menu look is off already."
[ ! -e "$grub/themes/monolith" ] || fail 'sync brought the theme back while off'
out="$(menu on)"
has "$out" 'is on /boot. It shows'
[ ! -e "$state/boot-menu-off" ] || fail 'on left the note'
[ -f "$grub/themes/monolith/theme.txt" ] && [ "$(count "$begin")" = 1 ] || fail 'on did not bring the look back'
[ -d "$grub/themes/another" ] || fail "on removed a theme that isn't Monolith's"
tidy
# With nothing else in user.cfg, off removes the file and the empty themes folder.
reset
menu sync >/dev/null
menu off >/dev/null
[ ! -e "$grub/user.cfg" ] || fail "off left a user.cfg behind: $(cat "$grub/user.cfg")"
[ ! -e "$grub/themes" ] || fail 'off left an empty themes folder'
# Off on a computer that never had the look writes nothing but the note.
reset
has "$(menu off)" "Monolith's boot menu look is off already."
[ ! -e "$grub/user.cfg" ] && [ ! -e "$grub/themes" ] || fail 'off wrote to a /boot that had no look'

# ---- An update brings a new look ---------------------------------------------
reset
menu sync >/dev/null
echo '# a newer theme' >>"$vendor/monolith/grub/themes/monolith/theme.txt"
printf 'new' >"$vendor/monolith/grub/themes/monolith/extra.png"
rm -- "$vendor/monolith/grub/themes/monolith/select_c.png"
echo 'set pager=1' >>"$vendor/monolith/grub/user.cfg"
has "$(menu sync)" 'is on /boot. It shows'
diff -r -- "$vendor/monolith/grub/themes/monolith" "$grub/themes/monolith" || fail 'the new theme was not copied whole'
grep -qx 'set pager=1' "$grub/user.cfg" || fail 'the new settings were not written'
[ "$(count "$begin")" = 1 ] || fail 'the new block was added next to the old one'
tidy

# ---- Where it can't or mustn't work ------------------------------------------
# No GRUB config at all.
reset
rm -- "$grub/grub.cfg"
has "$(menu sync)" "so there is no boot menu to change"
[ ! -e "$grub/user.cfg" ] && [ ! -e "$grub/themes" ] || fail 'wrote to a /boot without grub.cfg'
# A grub.cfg that never reads user.cfg.
reset
echo 'set timeout=1' >"$grub/grub.cfg"
has "$(menu sync)" "doesn't read user.cfg, so Monolith's look can't be turned on here."
[ ! -e "$grub/user.cfg" ] && [ ! -e "$grub/themes" ] || fail 'wrote a look GRUB would never read'
# A build without the look, or with only part of it: fail and leave /boot alone.
for part in user.cfg themes/monolith/theme.txt themes/monolith/theme-2x.txt themes/monolith/theme-2x-logo.txt; do
    reset
    menu sync >/dev/null
    rm -- "$image/$part"
    if out="$(menu sync 2>&1)"; then fail "sync should fail without the image's $part: $out"; fi
    has "$out" 'has no boot menu look'
    diff -r -x "${part##*/}" -- "$image/themes/monolith" "$grub/themes/monolith" && [ "$(count "$begin")" = 1 ] ||
        fail 'a failed sync changed /boot'
done
# Without root, /boot/grub2 can be neither read nor written.
if [ "$(id -u)" != 0 ]; then
    reset
    chmod 500 "$grub"
    if out="$(menu sync 2>&1)"; then fail "sync should fail on a /boot it can't write: $out"; fi
    has "$out" 'Changing the boot menu needs root.'
    chmod 000 "$grub"
    if out="$(menu sync 2>&1)"; then fail "sync should fail on a /boot it can't read: $out"; fi
    has "$out" "needs root."
    chmod 700 "$grub"
    [ ! -e "$grub/user.cfg" ] && [ ! -e "$grub/themes" ] || fail 'wrote despite failing'
fi

# ---- Screens with twice the pixels --------------------------------------------
# screen WIDTH HEIGHT [KIND]: the screen the kernel says GRUB handed it at this
# start, as it is in the boot parameters: the kind in byte 15 (112 is a UEFI
# screen), then width and height as two 16 bit numbers from byte 18.
byte() { printf '%b' "\\x$(printf '%02x' "$1")"; }
screen() {
    mkdir -p "$sys/kernel/boot_params"
    head -c 4096 /dev/zero >"$sys/kernel/boot_params/data"
    byte "${3:-112}" | dd of="$sys/kernel/boot_params/data" bs=1 seek=15 conv=notrunc status=none
    { byte $(($1 & 255)); byte $(($1 >> 8)); byte $(($2 & 255)); byte $(($2 >> 8)); } |
        dd of="$sys/kernel/boot_params/data" bs=1 seek=18 conv=notrunc status=none
}
# efi NAME VALUE: an EFI variable as the kernel shows it, its four bytes of
# attributes first.
efi() {
    mkdir -p "$sys/firmware/efi/efivars"
    { printf '\x06\x00\x00\x00'; byte "$2"; } >"$sys/firmware/efi/efivars/$1"
}
secure_boot() {
    efi SecureBoot-8be4df61-93ca-11d2-aa0d-00e098032b8c "$1"
    efi SetupMode-8be4df61-93ca-11d2-aa0d-00e098032b8c 0
}
# start: the computer starts again, so sync looks once more at what GRUB did.
start() { rm -f -- "$run/monolith-boot-menu-seen"; }
# knows NATIVE HALF: what sync has written down about the screen.
knows() {
    local is
    is="$(grep -v '^#' "$state/boot-menu-screen" 2>/dev/null | tr '\n' ' ')"
    [ "$is" = "native=$1 half=$2 " ] || fail "expected native=$1 half=$2, the note says: $is"
}
# asks: the half size the block tells GRUB to ask for, or nothing.
asks() { sed -n -E 's/^set monolith_half=(.*)$/\1/p' "$grub/user.cfg"; }
unchanged() { has "$(menu sync)" "Monolith's boot menu look is on /boot already."; }
written() { has "$(menu sync)" "Monolith's boot menu look is on /boot. It shows the next time the computer starts."; }

# A 1920x1080 screen: the block is the shipped user.cfg and nothing else.
reset
screen 1920 1080
written
[ "$(sed '1d;$d' "$grub/user.cfg")" = "$(cat "$shipped/user.cfg")" ] || fail 'a 1080p computer got more than the shipped settings'
knows 1920x1080 ''
lacks "$(menu)" "This computer's screen"

# Which sizes count as twice the pixels: 1800 pixels tall or more.
for size in '2560 1440 1' '3440 1440 1' '2560 1600 1' '5120 1440 1' '2880 1799 1' \
    '2880 1800 2' '3840 2160 2' '3000 2000 2' '5120 2880 2' '3840 2400 2'; do
    # shellcheck disable=SC2086
    set -- $size
    reset
    screen "$1" "$2"
    menu sync >/dev/null
    if [ "$3" = 2 ]; then
        [ "$(count 'set monolith_scale=2')" = 1 ] || fail "$1x$2 should get the large menu"
        [ "$(asks)" = "$(($1 / 2))x$(($2 / 2))" ] || fail "$1x$2 should ask for half its size, asks for: $(asks)"
    else
        [ "$(count 'set monolith_scale=2')" = 0 ] && [ -z "$(asks)" ] || fail "$1x$2 should get the normal menu"
    fi
done

# 3840x2160, Secure Boot off. At the first start GRUB still shows its plain
# menu, on the screen as the firmware left it.
reset
screen 3840 2160
written
[ "$(sed -n 1p "$grub/user.cfg")" = "$begin" ] || fail 'the block does not start user.cfg'
[ "$(sed -n 2p "$grub/user.cfg")" = 'set monolith_scale=2' ] || fail "the scale should follow the block's first line"
[ "$(sed -n 3p "$grub/user.cfg")" = 'set monolith_half=1920x1080' ] || fail 'the half size should follow the scale'
[ "$(sed '1,3d;$d' "$grub/user.cfg")" = "$(cat "$shipped/user.cfg")" ] || fail 'the rest of the block is not the shipped user.cfg'
[ "$(stat -c %a "$grub/user.cfg")" = 600 ] || fail 'user.cfg mode'
for file in logo-2x.png select-2x_w.png select-2x_c.png select-2x_e.png theme-2x.txt theme-2x-logo.txt; do
    [ -f "$grub/themes/monolith/$file" ] || fail "$file is not on /boot"
done
knows 3840x2160 ''
# A second sync in the same start: the new block is one GRUB hasn't read.
unchanged
knows 3840x2160 ''
# From the second start on GRUB draws the large menu on the same screen.
start
before="$(stat -c '%i %Y' "$grub/user.cfg" "$grub/themes/monolith" "$state/boot-menu-screen")"
unchanged
[ "$(stat -c '%i %Y' "$grub/user.cfg" "$grub/themes/monolith" "$state/boot-menu-screen")" = "$before" ] ||
    fail 'a start with nothing new wrote something'
has "$(menu)" "This computer's screen is 3840x2160, so the menu is drawn at twice the size."
[ "$(menu | awk 'length > 80')" = '' ] || fail 'the status has lines over 80 characters'
tidy

# 3840x2160, Secure Boot on, and the firmware has 1920x1080: GRUB asked for it
# and the kernel was handed it.
reset
secure_boot 1
screen 3840 2160
written
knows 3840x2160 ''
start
screen 1920 1080
unchanged
knows 3840x2160 yes
[ "$(asks)" = 1920x1080 ] || fail 'the half size was dropped although the firmware has it'
has "$(menu)" "at 1920x1080 and the screen scales it up."
[ "$(menu | awk 'length > 80')" = '' ] || fail 'the status has lines over 80 characters'
start
unchanged
knows 3840x2160 yes
# The note went missing: the half size GRUB was given says what the screen is.
rm -- "$state/boot-menu-screen"
start
unchanged
knows 3840x2160 yes

# 3840x2160, Secure Boot on, and the firmware has no such mode: GRUB asked and
# still had 3840x2160. The half size is dropped, and only the logo grows.
reset
secure_boot 1
screen 3840 2160
written
# Not yet: in this start GRUB can't have read the block that asks.
unchanged
knows 3840x2160 ''
[ "$(asks)" = 1920x1080 ] || fail 'the half size was dropped before GRUB could ask for it'
start
written
knows 3840x2160 no
[ "$(count 'set monolith_scale=2')" = 1 ] || fail 'the scale went with the half size'
[ -z "$(asks)" ] || fail "GRUB is still told to ask for $(asks)"
[ "$(sed '1,2d;$d' "$grub/user.cfg")" = "$(cat "$shipped/user.cfg")" ] || fail 'the block without a half size is not scale plus shipped user.cfg'
has "$(menu)" "mode of half that size, so only the logo is drawn at twice the size."
[ "$(menu | awk 'length > 80')" = '' ] || fail 'the status has lines over 80 characters'
start
unchanged
knows 3840x2160 no
# "on" has GRUB ask once more, for a firmware that learned the mode since.
has "$(menu on)" 'is on /boot. It shows'
knows 3840x2160 ''
[ "$(asks)" = 1920x1080 ] || fail '"on" did not bring the half size back'
start
written
knows 3840x2160 no
# The service's own sync never asks again by itself.
start
unchanged
[ -z "$(asks)" ] || fail 'a plain sync asked again'
tidy

# Secure Boot on in the firmware, but GRUB isn't locked down: shim's own
# switch is off, or the firmware is in setup mode. GRUB then draws the large
# menu and asks for nothing, so 3840x2160 says nothing about the half size.
for unlock in 'MokSBStateRT-605dab50-e046-4300-abb6-3dd810dd8b23' 'SetupMode-8be4df61-93ca-11d2-aa0d-00e098032b8c'; do
    reset
    secure_boot 1
    efi "$unlock" 1
    screen 3840 2160
    written
    start
    unchanged
    knows 3840x2160 ''
    [ "$(asks)" = 1920x1080 ] || fail "with $unlock set the half size was dropped"
    has "$(menu)" "so the menu is drawn at twice the size."
done
# Secure Boot off, said in so many words.
reset
secure_boot 0
screen 3840 2160
written
start
unchanged
knows 3840x2160 ''

# The screen is swapped for a smaller one. With Secure Boot off GRUB's own
# size shows it at the next start.
reset
screen 3840 2160
written
start
screen 1920 1080
written
knows 1920x1080 ''
[ "$(count 'set monolith_scale=2')" = 0 ] && [ -z "$(asks)" ] || fail 'the large menu stayed on a 1920x1080 screen'
# And for a larger one.
start
screen 3840 2160
written
knows 3840x2160 ''
[ "$(count 'set monolith_scale=2')" = 1 ] || fail 'the large menu did not come back'

# With Secure Boot on GRUB runs at the half it asked for. A smaller screen
# whose firmware has that mode too gets the menu at that size, and nothing
# is rewritten at each start.
reset
secure_boot 1
screen 3840 2160
written
start
screen 1920 1080
unchanged
knows 3840x2160 yes
start
unchanged
knows 3840x2160 yes
# Off, a start, and on again measure the screen anew: with the look off GRUB
# takes the screen as the firmware left it.
menu off >/dev/null
start
has "$(menu sync)" "Monolith's boot menu look is off already."
knows 1920x1080 ''
has "$(menu on)" 'is on /boot. It shows'
[ "$(count 'set monolith_scale=2')" = 0 ] && [ -z "$(asks)" ] || fail 'the large menu came back on a 1920x1080 screen'

# Secure Boot on, and another screen whose firmware hasn't the old half size
# either: that is a new screen, not a "no" for its own half.
reset
secure_boot 1
screen 3840 2160
written
start
screen 3000 2000
written
knows 3000x2000 ''
[ "$(asks)" = 1500x1000 ] || fail "a new screen should be asked for its own half, asks for: $(asks)"
# The same after the old screen's half had worked: what was learned about
# the old screen says nothing about the new one.
reset
secure_boot 1
screen 3840 2160
written
start
screen 1920 1080
unchanged
knows 3840x2160 yes
start
screen 3000 2000
written
knows 3000x2000 ''
[ "$(asks)" = 1500x1000 ] || fail "a new screen should be asked for its own half, asks for: $(asks)"
start
written
knows 3000x2000 no

# What the kernel doesn't say isn't guessed.
reset
written
[ "$(count 'set monolith_scale=2')" = 0 ] || fail 'a computer that says nothing about its screen got the large menu'
[ ! -e "$state/boot-menu-screen" ] || fail 'a note was written about a screen nothing is known of'
# A text screen (kind 1) has no size in pixels.
reset
screen 3840 2160 1
written
[ "$(count 'set monolith_scale=2')" = 0 ] || fail 'a text screen was taken for a large one'
# The kernel's note is empty, cut short or not to be read.
for damage in empty short unreadable; do
    reset
    screen 3840 2160
    case "$damage" in
        empty) : >"$sys/kernel/boot_params/data" ;;
        short) head -c 19 /dev/zero >"$sys/kernel/boot_params/data" ;;
        unreadable) chmod 000 "$sys/kernel/boot_params/data" ;;
