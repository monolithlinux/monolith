# ---- What GRUB makes of user.cfg ---------------------------------------------
# user.cfg is a GRUB script, and the part of GRUB's language it uses is the
# shell's. So the file sync wrote is run here the way GRUB would run it, with
# stand-ins for GRUB's own commands, to see what comes out of it: the theme,
# the mode GRUB asks the firmware for and the fonts it was told to load.
# grub_reads LOCKDOWN [damaged]: LOCKDOWN is y when Secure Boot is on, as in
# GRUB. "damaged" makes the font on /boot fail to load.
# Prints THEME|GFXMODE|FONTS|TIMEOUT|what is left of Monolith's own variables.
grub_reads() {
    # The variables and stand-ins below are used by user.cfg, not by this file.
    # shellcheck disable=SC2034,SC2329
    (
        builtin set +eu
        cd -- "$grub" || exit 1
        lockdown="$1" font="${2-}" prefix=. fonts="" theme="" gfxmode="" timeout=""
        set() { local pair; for pair in "$@"; do printf -v "${pair%%=*}" '%s' "${pair#*=}"; done; }
        insmod() { :; }
        terminal_output() { :; }
        # GRUB has its own font inside it. One from the disk it only reads when
        # it isn't locked down.
        loadfont() {
            fonts="$fonts ${1#./themes/monolith/}"
            [[ $1 == unicode ]] || [[ $lockdown != y && $font != damaged && -s $1 ]]
        }
        # shellcheck disable=SC1091
        source ./user.cfg
        printf '%s|%s|%s|%s|%s\n' "${theme#./themes/monolith/}" "$gfxmode" "${fonts# }" "$timeout" \
            "${monolith_scale-}${monolith_half-}${monolith_theme-}"
    )
}
# reads WANTED LOCKDOWN [damaged]
reads() {
    local is
    is="$(grub_reads "${@:2}")"
    [ "$is" = "$1|5|" ] || fail "GRUB with lockdown='$2' ${3-}: expected $1|5|, got $is"
}
